"""Resolve pointers in Markdown. One function feeds every view: the committed GitLab copy
(links only, never prose), the browser site (links to generated standard pages), and the
terminal (titles inline, text appended)."""
from __future__ import annotations

import os
from pathlib import Path
from typing import Callable

from ..canon.client import Canon, Pointer, Standard
from ..canon.reconcile import doc_files

RENDERED_REL = Path("docs/rendered")
HEADER = "<!-- ds:rendered from {src}; generated by `ds docs render`; pointers resolved to links, never prose; do not edit -->\n\n"


def label(std: Standard, pinned: int | None = None) -> str:
    v = f"v{pinned}, canon v{std.version}" if pinned is not None and pinned != std.version else f"v{std.version}"
    return f"{std.title} ({std.id} {v})"


def resolve_text(text: str, canon: Canon, link_for: Callable[[Standard], str] | None) -> str:
    """Replace every ``[[id]]`` with ``[Title (id vN)](link)``, or with the bare label when
    ``link_for`` is None. Unknown ids are left as written so ``check`` can report them."""
    def sub(ptr: Pointer) -> str:
        try:
            res = canon.resolve(ptr.id, ptr.pinned)
        except Exception:
            return ptr.raw
        text_label = label(res.standard, ptr.pinned)
        return f"[{text_label}]({link_for(res.standard)})" if link_for else text_label
    out = text
    for ptr in sorted(canon.pointers(text), key=lambda p: -p.start):
        out = out[:ptr.start] + sub(ptr) + out[ptr.end:]
    return out


def render_repo(repo: Path, canon: Canon, out_dir: Path | None = None, canon_url: str | None = None) -> list[tuple[Path, bool]]:
    """Write the GitLab copy: every doc file mirrored under ``docs/rendered/`` with pointers
    resolved to links into the canon (``canon_url`` for a web host, else a relative path to
    the local checkout). Returns ``(path, changed)`` per file; a second run changes nothing."""
    repo = Path(repo).resolve()
    out_dir = Path(out_dir) if out_dir else repo / RENDERED_REL
    written: list[tuple[Path, bool]] = []
    for src in doc_files(repo):
        rel = src.relative_to(repo)
        dst = out_dir / rel

        def link_for(std: Standard, _dst: Path = dst) -> str:
            if canon_url:
                return f"{canon_url.rstrip('/')}/{std.path}"
            return os.path.relpath(canon.root / std.path, _dst.parent)

        content = HEADER.format(src=rel.as_posix()) + resolve_text(src.read_text(), canon, link_for)
        changed = not dst.exists() or dst.read_text() != content
        if changed:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(content)
        written.append((dst, changed))
    return written


def print_docs(repo: Path, canon: Canon, files: tuple[str, ...] = ("README.md", "AGENTS.md"), inline: bool = False) -> str:
    """The terminal view: titles inline; with ``inline`` the referenced standards' text follows."""
    repo = Path(repo)
    parts: list[str] = []
    seen: dict[str, Standard] = {}
    for name in files:
        p = repo / name
        if not p.exists():
            continue
        text = p.read_text()
        for ptr in canon.pointers(text):
            try:
                seen[ptr.id] = canon.get(ptr.id)
            except Exception:
                pass
        parts.append(f"━━ {name} ━━\n" + resolve_text(text, canon, None).rstrip("\n") + "\n")
    if inline and seen:
        parts.append("━━ Standards referenced ━━\n")
        for sid, std in sorted(seen.items()):
            body = canon.body(std).rstrip("\n").replace("\n", "\n    ")
            parts.append(f"{label(std)}  [{std.path}]\n    {body}\n")
    return "\n".join(parts)
